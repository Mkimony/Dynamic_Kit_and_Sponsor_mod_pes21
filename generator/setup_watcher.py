#!/usr/bin/env python3
r"""setup_watcher.py - deploy the kit generator into the game and write watcher.cmd.

Run this once (re-run after moving the mod or changing Python).  It

  1. copies this generator folder (the .py files, clubs.csv and uv_masks/) into
         <game>\SiderAddons\KitGenerator\generator\
     so the watcher is self-contained inside the game and no longer depends on
     wherever the mod source happens to live, and
  2. writes
         <game>\SiderAddons\content\KitGenerator\watcher.cmd
     which launches watch_signed.py with pythonw (no console window).

KitGenerator.lua starts watcher.cmd automatically when the game loads, so from
then on a signed sponsor deal rebuilds that season's kits by itself.

Usage
-----
    python setup_watcher.py
    python setup_watcher.py --game-root "D:\Games\SP Football Life 2027"
"""
import argparse
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # ...\generator
MOD_ROOT = HERE.parent                          # the mod root (holds content/, modules/)
DEFAULT_GAME_ROOT = Path(r"C:\Program Files (x86)\SP Football Life 2027")

# what we copy into the game, relative to this generator folder
COPY_FILES = ("*.py",)
COPY_NAMES = ("clubs.csv",)
COPY_DIRS = ("uv_masks",)

# what we copy into <sider>\content\KitGenerator (logos + the offer list).  The
# live state files there (career.txt, watcher_state.txt, kit_request.txt,
# watcher.log) are never touched.  brands.txt is generated from the logos, not
# copied, so it always matches the logos that actually shipped.
CONTENT_FILES = ("deals.txt",)
CONTENT_DIRS = ("logos",)


def brand_names(logo_dir):
    """The brand pool: logo file stems, without the `_white` variants."""
    return sorted({p.stem for p in Path(logo_dir).glob("*.png")
                   if not p.stem.endswith("_white") and not p.stem.startswith("_")})


def write_brands(sider):
    """Write content/KitGenerator/brands.txt from the deployed logos.

    KitGenerator.lua reads this to synthesise offers for a club that deals.txt
    does not cover.  Returns (path, brand count).
    """
    root = Path(sider) / "content" / "KitGenerator"
    names = brand_names(root / "logos")
    out = root / "brands.txt"
    text = ("# brand pool - generated by setup_watcher.py from the logo files.\n"
            "# KitGenerator.lua uses it to offer deals to clubs deals.txt does not cover.\n"
            + "".join(n + "\n" for n in names))
    out.write_text(text, encoding="utf-8", newline="")
    return out, len(names)


def _pythonw():
    exe = Path(sys.executable)
    cand = exe.with_name("pythonw.exe")
    return cand if cand.is_file() else exe


def deploy_generator(dest):
    """Copy the generator into `dest`; returns the number of files copied."""
    dest.mkdir(parents=True, exist_ok=True)
    n = 0
    if dest.resolve() == HERE.resolve():
        return 0                                 # already running from the target
    for pat in COPY_FILES:
        for src in HERE.glob(pat):
            shutil.copy2(src, dest / src.name)
            n += 1
    for name in COPY_NAMES:
        src = HERE / name
        if src.is_file():
            shutil.copy2(src, dest / name)
            n += 1
    for name in COPY_DIRS:
        src = HERE / name
        if src.is_dir():
            dst = dest / name
            shutil.copytree(src, dst, dirs_exist_ok=True)
            n += sum(1 for _ in dst.rglob("*") if _.is_file())
    return n


def deploy_content(sider):
    """Copy logos/ and deals.txt into <sider>\\content\\KitGenerator.

    Existing brand logos are overwritten with the mod's copies (the mod is the
    source of truth) but the live state files are left alone.  Returns the
    number of files copied.
    """
    src_root = MOD_ROOT / "content" / "KitGenerator"
    dst_root = Path(sider) / "content" / "KitGenerator"
    dst_root.mkdir(parents=True, exist_ok=True)
    n = 0
    for name in CONTENT_FILES:
        src = src_root / name
        if src.is_file():
            shutil.copy2(src, dst_root / name)
            n += 1
    for name in CONTENT_DIRS:
        src = src_root / name
        if src.is_dir():
            dst = dst_root / name
            dst.mkdir(parents=True, exist_ok=True)
            for f in src.rglob("*"):
                if f.is_file():
                    target = dst / f.relative_to(src)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(f, target)
                    n += 1
    return n


def write_cmd(sider, game_root):
    """Write content/KitGenerator/watcher.cmd; returns its path."""
    content = Path(sider) / "content" / "KitGenerator"
    content.mkdir(parents=True, exist_ok=True)
    cmd = content / "watcher.cmd"
    py = _pythonw()
    script = Path(sider) / "KitGenerator" / "generator" / "watch_signed.py"
    text = (
        "@echo off\r\n"
        "rem KitGenerator watcher - auto-started by KitGenerator.lua at game load.\r\n"
        "rem Regenerate with:  python \"%s\"\r\n"
        "start \"\" /b \"%s\" \"%s\" --sider \"%s\" --game-root \"%s\"\r\n"
        % (HERE / "setup_watcher.py", py, script, sider, game_root)
    )
    cmd.write_text(text, encoding="utf-8", newline="")
    return cmd


def clean_legacy_override(sider):
    """Delete the old static livecpk kit overrides.

    Earlier versions installed u<team>p<slot>.ftex under
    livecpk\\KitGenerator\\Asset\\...\\#windx11, which the cpk.root list applies
    in EVERY game mode.  The generated kits now live in content\\kits\\
    _KitGenerator and are served only in Master League, so any leftover static
    override must go.  Returns the number of files removed.
    """
    root = (Path(sider) / "livecpk" / "KitGenerator" / "Asset" / "model" /
            "character" / "uniform" / "texture" / "#windx11")
    n = 0
    if root.is_dir():
        for f in root.glob("u*p[123].ftex"):
            try:
                f.unlink()
                n += 1
            except OSError:
                pass
    return n


def ensure_cpk_root(sider):
    """Make sider.ini serve content\\kits, and stop serving livecpk\\KitGenerator.

    The generated kits are handed to Sider as the key
    ``_KitGenerator\\u<team>p<slot>.ftex``.  Registering ``.\\content\\kits`` as a
    cpk.root makes that key resolve to our private store directly, so the kit
    loads even if a future Sider version does not consult get_filepath for
    make_key results.  The old ``.\\livecpk\\KitGenerator`` root is dropped so a
    stale override can never be applied in a non-career mode.

    Returns (changed, note) where note is a short human description.
    """
    ini = Path(sider) / "sider.ini"
    if not ini.is_file():
        return False, "sider.ini not found"
    text = ini.read_text(encoding="utf-8", errors="replace")
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.split(nl)

    keep, dropped = [], 0
    for ln in lines:
        if ln.strip() == 'cpk.root = ".\\livecpk\\KitGenerator"':
            dropped += 1
            continue
        keep.append(ln)

    have_store = any(ln.strip() == 'cpk.root = ".\\content\\kits"' for ln in keep)
    if not have_store:
        idx = next((i for i, ln in enumerate(keep)
                    if ln.strip().startswith("cpk.root")), len(keep))
        keep.insert(idx, 'cpk.root = ".\\content\\kits"')

    if not dropped and have_store:
        return False, "already correct"
    ini.write_text(nl.join(keep), encoding="utf-8", newline="")
    bits = []
    if not have_store:
        bits.append("added content\\kits root")
    if dropped:
        bits.append(f"removed {dropped} livecpk\\KitGenerator root(s)")
    return True, ", ".join(bits)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game-root", default=str(DEFAULT_GAME_ROOT),
                    help="game install root (default: %(default)s)")
    ap.add_argument("--sider", default=None,
                    help="SiderAddons folder (default: <game-root>\\SiderAddons)")
    args = ap.parse_args(argv)

    game_root = Path(args.game_root)
    sider = Path(args.sider) if args.sider else game_root / "SiderAddons"
    if not sider.is_dir():
        raise SystemExit(f"SiderAddons not found: {sider}")

    dest = sider / "KitGenerator" / "generator"
    n = deploy_generator(dest)
    nc = deploy_content(sider)
    brands, nb = write_brands(sider)
    cmd = write_cmd(sider, game_root)
    removed = clean_legacy_override(sider)
    changed, note = ensure_cpk_root(sider)

    print(f"deployed {n} file(s) -> {dest}")
    print(f"deployed {nc} file(s) -> {sider / 'content' / 'KitGenerator'} (logos, deals.txt)")
    print(f"wrote {nb} brand(s)  -> {brands}")
    print(f"wrote launcher        -> {cmd}")
    print(f"pythonw               -> {_pythonw()}")
    print(f"sider.ini             -> {'updated: ' + note if changed else note}")
    if removed:
        print(f"removed {removed} legacy livecpk kit override(s) (now ML-only via the store)")
    print()
    print("KitGenerator.lua will start the watcher automatically next time you "
          "launch the game.")
    print("To test it now without the game:")
    print(f'  "{_pythonw()}" "{dest / "watch_signed.py"}" --sider "{sider}" --once')
    return 0


if __name__ == "__main__":
    sys.exit(main())
